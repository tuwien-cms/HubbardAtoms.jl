"""Generate the certificate modules of the longitudinal completion.

Run: python gen.py OUTDIR
Writes FieldLCertData.lean (the polynomials) and FieldLCert{W,Z}{A,B}.lean (the certificates).
"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from analysis import *

LEANVAR = {'u': 'u', 'v': 'x', 's': 's', 'a': 'a', 'w': 'w', 'b': 'β', 'P0': 'P', 'rh': 'ρ', 'M': 'M'}
ORDER = ['u', 'x', 's', 'a', 'w', 'β', 'P', 'ρ', 'M']


def lean_poly(p):
    if p.is_zero():
        return '0'
    terms = []
    for mon, c in sorted(p.to_dict().items(), reverse=True):
        num, den = int(c.p), int(c.q)
        factors = []
        for name, e in zip(NAMES, mon):
            e = int(e)
            if e == 0:
                continue
            var = LEANVAR[name]
            factors.append(var if e == 1 else f'{var} ^ ({e} : ℕ)')
        mag = abs(num)
        coef = '' if (mag == 1 and den == 1 and factors) else (f'{mag}' if den == 1 else f'({mag} / {den})')
        body = ' * '.join(([coef] if coef else []) + factors) or '1'
        terms.append(('-' if num < 0 else '+', body))
    out = ('-' + terms[0][1]) if terms[0][0] == '-' else terms[0][1]
    for sg, body in terms[1:]:
        out += f' {sg} {body}'
    return out


def wrap(expr, indent=4, width=98):
    toks = re.split(r'( [+-] )', expr)
    lines, cur = [], ' ' * indent + toks[0]
    i = 1
    while i < len(toks):
        piece = toks[i] + toks[i + 1]
        if len(cur) + len(piece) > width:
            lines.append(cur)
            cur = ' ' * indent + piece.lstrip()
        else:
            cur += piece
        i += 2
    lines.append(cur)
    return '\n'.join(lines)


def to_x(p):
    """even polynomial in v -> polynomial in x = v² (x kept in the slot of v)."""
    d = {}
    i = NAMES.index('v')
    for mon, c in p.to_dict().items():
        assert mon[i] % 2 == 0
        d[mon[:i] + (mon[i] // 2,) + mon[i + 1:]] = c
    return ctx.from_dict(d)


def used_vars(p):
    if p.is_zero():
        return set()
    return {LEANVAR[NAMES[i]] for i, e in enumerate(p.degrees()) if int(e) > 0}


HEADER_DATA = '''import Mathlib.Analysis.Complex.Basic

/-!
# The polynomials of the longitudinal completion (generated)

**Generated by `scripts/longitudinal_certificates.py`; do not edit.**

The polynomial data of the completion of the longitudinal inverse, Eq. (field-L) of the note, for a
column of spin `t`, in free variables: the root `u` (or `x = v²`), the thermal value `s = S_t(u)`,
`a = U/2`, `w = iω_k`, `β`, and the weights through `P = p₀ + p₂`, `ρ = p₂ - p₀`,
`M = p_t - p_{-t}` (so `p₀ = (P - ρ)/2`, `p₂ = (P + ρ)/2`, `p_t = (1 - P + M)/2`,
`p_{-t} = (1 - P - M)/2`). Suffix `W` is `k ≠ 0`; suffix `Z` is `k = 0` (`w = 0`, `δ_k0 = 1`).

* `E8W`, `E8Z`, `E6Z`: `E₈(u)`, and `E₆ = E₈/(u² - a²)` at `k = 0`.
* `NcW`/`NcZ` + row + `c`: the completed defect of the coefficient of `zᶜ` in the row `t` (row `0`)
  or `-t` (row `1`), times `βE₈(v)`, a polynomial of degree at most three in `x = v²`.
* `McW`/`McZ` + row + `c`: the coefficient of `zᶜ` in the image of `P(u)Φ` under `P(z)χ_L`, with
  `Φ` the mode of the root `u` normalized with the column spin, affine in `s`.
* `KtW`, `KtZ`: the thermal denominator `K_t` of the mode; `aAW`, `aAZ`: `a_t = 2λ²D_t(u² + q₀)`,
  so that the coefficient of the mode in Eq. (field-L-mode) is `𝔠 ∝ a_t/K_t`.
-/

namespace HubbardAtom

namespace LCert
'''

HEADER_CERT = '''import HubbardAtomLean.FieldLCertData
import Mathlib.Tactic.LinearCombination

/-!
# Certificates of the longitudinal completion, {what} (generated)

**Generated by `scripts/longitudinal_certificates.py`; do not edit.**

Each identity `β²N_c(u²)K_t = β a_t M_c` (the residue of the completed defect at a root `u` matches
the image of the mode, Eq. (field-L-mode)) holds modulo `{E}(u)`; it is closed by `linear_combination` with the exact quotient,
computed over `ℚ` with python-flint. The polynomials are those of `FieldLCertData.lean`.
-/

namespace HubbardAtom

namespace LCert

set_option Elab.async false
'''


def main(outdir):
    data = [HEADER_DATA]
    certs = {}
    SIG = {}

    def defpoly(name, p, doc):
        used = used_vars(p)
        sig = [x for x in ORDER if x in used]
        SIG[name] = sig
        data.append(f'/-- {doc} -/')
        data.append(f'noncomputable def {name} ({" ".join(sig)} : ℂ) : ℂ :=')
        data.append(wrap(lean_poly(p)))
        data.append('')

    def call(name, **vals):
        args = []
        for x in SIG[name]:
            val = vals.get(x, x)
            args.append(val if re.fullmatch(r'[A-Za-zα-ωΑ-Ω]+', val) else f'({val})')
        return ' '.join([name] + args)

    for k0 in (False, True):
        sfx = 'Z' if k0 else 'W'
        m = Model(k0)
        E8u = m.E8(u)
        defpoly(f'E8{sfx}', E8u, f'`E₈(u)`, `k {"=" if k0 else "≠"} 0`.')
        if k0:
            E6u = E8u / (u ** 2 - a ** 2)
            assert E6u * (u ** 2 - a ** 2) == E8u
            defpoly('E6Z', E6u, '`E₆(u) = E₈(u)/(u² - a²)`, `k = 0`.')
            Eu, Ename = E6u, 'E6Z'
        else:
            Eu, Ename = E8u, 'E8W'
        _, D = dense(m)
        _, Mi = mode_image(m)
        ftp, ftm, fnp, fnm = mode(m)
        Kt, Kn = (ftp + ftm), (fnp + fnm)
        assert Kt.d.is_one() and Kn.d.is_one()
        defpoly(f'Kt{sfx}', Kt.n, '`K_t = f_{t+} + f_{t-}`.')
        defpoly(f'Kn{sfx}', Kn.n, '`K_{-t} = f_{-t,+} + f_{-t,-}`.')
        lam, q0 = m.lam, m.q0
        aA = 2 * lam ** 2 * m.Dt * (u ** 2 + q0)
        x2 = u ** 2
        Xi = (x2 + q0) ** 2 - 4 * a ** 2 * m.rt * m.rn * x2 - lam ** 2 * m.dpi
        Pi = (x2 + q0) ** 2 + 4 * a ** 2 * m.rt * m.rn * x2 + lam ** 2 * m.dpi
        bW = -lam * (rh * Xi + M * Pi)
        defpoly(f'aA{sfx}', aA, '`2λ²D_t(u² + q₀)`.')
        defpoly(f'bW{sfx}', bW, '`-λ(ρΞ + MΠ)`.')
        certs[(sfx, 'A')] = []
        for ri, row in enumerate(('t', 'n')):
            for c in range(3):
                tot = D[row][c]
                g = tot.d.gcd(m.E8(v))
                assert tot.d / g == b
                N = tot.n * (m.E8(v) / g)
                if k0:
                    assert subs(N, 'v', a).is_zero()
                defpoly(f'Nc{sfx}{ri}{c}', to_x(N),
                        f'The completed defect of `z^{c}` in row {"`t`" if ri == 0 else "`-t`"}, times `βE₈(v)`, in `x = v²`.')
                Mc = Mi[row][c]
                assert Mc.d.is_one()
                defpoly(f'Mc{sfx}{ri}{c}', Mc.n,
                        f'The coefficient of `z^{c}` of the image of `P(u)Φ` in row {"`t`" if ri == 0 else "`-t`"}.')
                Nu = subs(N, 'v', u)
                for form, K, num, kname, nname in (('A', Kt, aA, 'Kt', 'aA'),):
                    ident = F(b ** 2 * Nu) * K - F(b * num) * Mc
                    assert ident.d.is_one()
                    q, rr = divmod(ident.n, Eu)
                    assert rr.is_zero()
                    stmt = (lambda sfx=sfx, ri=ri, c=c, kname=kname, nname=nname:
                            f'β ^ 2 * {call(f"Nc{sfx}{ri}{c}", x="u ^ 2")} * {call(kname + sfx)} = '
                            f'β * {call(nname + sfx)} * {call(f"Mc{sfx}{ri}{c}")}')
                    certs[(sfx, form)].append((f'cert_{sfx}{ri}{c}', Ename, q, stmt,
                                               f'Completion of `z^{c}` in row {"`t`" if ri == 0 else "`-t`"}: `β²N(u²)K_t = βa_tM` modulo `E(u)`.'))
    data.append('end LCert\n\nend HubbardAtom')
    open(os.path.join(outdir, 'FieldLCertData.lean'), 'w').write('\n'.join(data) + '\n')
    for (sfx, form), lst in certs.items():
        E = 'E₈' if sfx == 'W' else 'E₆'
        what = 'k ≠ 0' if sfx == 'W' else 'k = 0'
        hdr = HEADER_CERT.replace('{what}', what).replace('{E}', E)
        if sfx == 'Z':
            hdr = hdr.replace('import HubbardAtomLean.FieldLCertData', 'import HubbardAtomLean.FieldLCertW')
        out = [hdr]
        for name, Ename, q, stmt, doc in lst:
            st = stmt()
            used = set(SIG[Ename])
            for nm in re.findall(r'\b((?:Kt|Kn|aA|bW|Nc|Mc)[WZ]\d*)\b', st):
                used |= set(SIG[nm])
            used.discard('x')
            used.add('u')
            if 'β ^ 2' in st:
                used.add('β')
            args = [x for x in ORDER if x in used]
            names = sorted(set(re.findall(r'\b((?:Kt|Kn|aA|bW|Nc|Mc)[WZ]\d*)\b', st)))
            out.append(f'/-- {doc} -/')
            out.append(f'theorem {name} ({" ".join(args)} : ℂ) (hE : {call(Ename)} = 0) :')
            out.append(f'    {st} := by')
            out.append(f'  unfold {Ename} at hE')
            out.append(f'  unfold {" ".join(names)}')
            out.append('  linear_combination (exp := 1) (')
            out.append(wrap(lean_poly(q), indent=6))
            out.append('    ) * hE')
            out.append('')
        out.append('end LCert\n\nend HubbardAtom')
        open(os.path.join(outdir, f'FieldLCert{sfx}.lean'), 'w').write('\n'.join(out) + '\n')
    return SIG


if __name__ == '__main__':
    SIG = main(sys.argv[1])
    for k_, v_ in SIG.items():
        print(k_, ' '.join(v_))
