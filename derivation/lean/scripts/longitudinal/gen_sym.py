"""Generate FieldLSymCert.lean: the identities behind the symmetry of the longitudinal inverse.

Run: python gen_sym.py OUTDIR

At a root `u` of `E₈`, with `s = S_t(u)` and the thermal values of the other spin from the product
relations, the numerator of the residue of `Γ_L(-t, z; t, v) - Γ_L(t, v; -t, z)` at
`v² = z² = u²` is a polynomial `α z + β v + γ z v + δ` whose coefficients vanish by (`γ` identically)

  z:  a_t K_{-t} = b_t K_t                                    (Eq. (field-L-quotient))
  v:  a_{-t} (G̃₊ + G̃₋) = b_{-t} K̃
  1:  8aλρm u²(u² + q₀) K_t K̃ - a_t (f_{-t,+} - f_{-t,-}) u K̃ + a_{-t} (G̃₊ - G̃₋) u K_t = 0

with the mode normalized with `t` (`f`, `K_σ = f_{σ+} + f_{σ-}`) and with `-t`
(`K̃ = (m s - c_S)K_{-t}`, `G̃± = (m s - c_S)g_{t±}`), `a_σ = 2λ²D_σ(u² + q₀)`, `b_σ = -λ(ρΞ + σmΠ)`.
None involves the rank-one terms of `k = 0`, so each holds modulo `E₈(u)` for all `k` (`w = iω_k`).
The last is certified coefficientwise in `s` (`E₈` does not involve `s`), which keeps each
certificate small.
"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen import lean_poly, wrap, used_vars, ORDER
from analysis import *

HDR = '''import HubbardAtomLean.FieldLCertData

/-!
# Certificates of the symmetry of the longitudinal inverse (generated)

**Generated by `scripts/longitudinal/gen_sym.py`; do not edit.**

At a root `u` of `E₈`, the residue of `Γ_L(-t, z; t, v) - Γ_L(t, v; -t, z)` at `v² = z² = u²`
vanishes by three identities in `s = S_t(u)` (two of them times `m s - c_S`); each holds modulo
`E₈(u)` for all `k` and is closed by `linear_combination` with the exact quotient.
-/

namespace HubbardAtom

namespace LCert

-- the certificates are large: elaborate them one at a time, to bound the memory
set_option Elab.async false
'''


def main(outdir):
    out = [HDR]
    SIG = {}

    def defpoly(name, p, doc):
        sig = [x for x in ORDER if x in used_vars(p)]
        SIG[name] = sig
        out.append(f'/-- {doc} -/')
        out.append(f'noncomputable def {name} ({" ".join(sig)} : ℂ) : ℂ :=')
        out.append(wrap(lean_poly(p)))
        out.append('')

    def call(name, **vals):
        args = []
        for x in SIG[name]:
            val = vals.get(x, x)
            args.append(val if val.isidentifier() else f'({val})')
        return ' '.join([name] + args)

    m = Model(False)
    Eu = m.E8(u)
    SIG['E8W'] = [x for x in ORDER if x in used_vars(Eu)]
    lam, q0, d = m.lam, m.q0, m.dpi
    Ht = lambda x: m.H(m.rt, x)
    Hn = lambda x: m.H(m.rn, x)
    s2, _, _ = chain(m)
    ftp, ftm, fnp, fnm = mode(m)
    Qn = Hn(-u) * Ht(u) * Ht(-u) - lam ** 2 * (m.piP * Ht(-u) + m.piS * Ht(u))
    den = F(M * s - m.cS)
    gnp = F(-b * Qn)
    gnm = F(2 * lam ** 2 * (u ** 2 + q0)) * (F(m.Dn) * s2 - F(b * m.cn, 2))
    gtp = F(-lam * (Hn(-u) * Ht(-u) + lam ** 2 * d)) * (-F(M) * s2 - F(m.cS))
    gtm = F(-lam * (Hn(-u) * Ht(u) - lam ** 2 * d)) * (F(rh) * s2 - F(m.cP))
    Kt, Kn = ftp + ftm, fnp + fnm
    KnS, GpS, GmS = (gnp + gnm) * den, gtp * den, gtm * den
    for P_ in (Kt, Kn, KnS, GpS, GmS, fnp, fnm):
        assert P_.d.is_one()
    x2 = u ** 2
    at = 2 * lam ** 2 * m.Dt * (x2 + q0)
    an = 2 * lam ** 2 * m.Dn * (x2 + q0)
    Xi = (x2 + q0) ** 2 - 4 * a ** 2 * m.rt * m.rn * x2 - lam ** 2 * d
    Pi = (x2 + q0) ** 2 + 4 * a ** 2 * m.rt * m.rn * x2 + lam ** 2 * d
    bW = -lam * (rh * Xi + M * Pi)
    bWn = -lam * (rh * Xi - M * Pi)
    for name, p_ in (('KtW', Kt.n), ('KnW', Kn.n), ('aAW', at), ('bWW', bW)):
        SIG[name] = [x for x in ORDER if x in used_vars(p_)]
    defpoly('FnpW', fnp.n, '`f_{-t,+}` of the mode normalized with `t`.')
    defpoly('FnmW', fnm.n, '`f_{-t,-}` of the mode normalized with `t`.')
    defpoly('KnSW', KnS.n, '`(m s - c_S)K_{-t}` of the mode normalized with `-t`.')
    defpoly('GpSW', GpS.n, '`(m s - c_S)g_{t+}` of the mode normalized with `-t`.')
    defpoly('GmSW', GmS.n, '`(m s - c_S)g_{t-}` of the mode normalized with `-t`.')
    defpoly('anW', an, '`a_{-t} = 2λ²D_{-t}(u² + q₀)`.')
    defpoly('bWnW', bWn, '`-λ(ρΞ - MΠ)`, the `bW` of the spin `-t`.')
    c = {n: call(n) for n in ('KtW', 'KnW', 'aAW', 'bWW', 'FnpW', 'FnmW', 'KnSW', 'GpSW', 'GmSW', 'anW',
                              'bWnW')}
    idents = [
        ('z', F(at) * Kn - F(bW) * Kt,
         [f"{c['aAW']} * {c['KnW']} - {c['bWW']} * {c['KtW']}"],
         '`a_tK_{-t} = b_tK_t`, Eq. (field-L-quotient)',
         ['aAW', 'KnW', 'bWW', 'KtW']),
        ('v', F(an) * (GpS + GmS) - F(bWn) * KnS,
         [f"{c['anW']} * ({c['GpSW']} + {c['GmSW']}) -", f"  {c['bWnW']} * {c['KnSW']}"],
         'the quotient identity of the spin `-t`',
         ['anW', 'GpSW', 'GmSW', 'bWnW', 'KnSW']),
    ]
    for tag, I, stmt, doc, names in idents:
        assert I.d.is_one()
        q, r = divmod(I.n, Eu)
        assert r.is_zero(), tag
        args = [x for x in ORDER if x in set().union(*(SIG[n] for n in names)) | {'u', 's', 'a', 'w'}]
        out.append(f'/-- At a root of `E₈`, {doc}. -/')
        out.append(f'theorem sym_{tag} ({" ".join(args)} : ℂ) (hE : {call("E8W")} = 0) :')
        stmt[-1] += ' = 0 := by'
        out.extend('    ' + ln for ln in stmt)
        out.append('  unfold E8W at hE')
        out.append(f'  unfold {" ".join(names)}')
        out.append('  linear_combination (exp := 1) (')
        out.append(wrap(lean_poly(q), indent=6))
        out.append('    ) * hE')
        out.append('')
        print(tag, 'numerator terms', len(I.n), 'quotient terms', len(q))
    # the constant part, split by powers of `s`: `E₈` does not involve `s`, so each coefficient
    # vanishes modulo `E₈` by itself, with much smaller certificates
    iS = NAMES.index('s')

    def split(p_):
        parts = ({}, {})
        for mon, cf in p_.to_dict().items():
            parts[int(mon[iS])][mon[:iS] + (0,) + mon[iS + 1:]] = cf
        return tuple(ctx.from_dict(d_) if d_ else ZERO for d_ in parts)

    pieces = {}
    for name, p_ in (('Kt', Kt.n), ('KnS', KnS.n), ('GmS', GmS.n), ('Fnp', fnp.n), ('Fnm', fnm.n)):
        assert deg(p_, 's') <= 1
        p0, p1 = split(p_)
        assert p0 + s * p1 == p_
        pieces[name] = (p0, p1)
        defpoly(f'{name}0W', p0, f'The part of `{name}W` without `s`.')
        defpoly(f'{name}1W', p1, f'The coefficient of `s` in `{name}W`.')
        out.append(f'theorem {name}W_split ({" ".join(SIG[name + "W"])} : ℂ) :')
        out.append(f'    {call(name + "W")} = {call(name + "0W")} + s * {call(name + "1W")} := by')
        out.append(f'  unfold {name}W {name}0W {name}1W')
        out.append('  ring')
        out.append('')
    (Kt0, Kt1), (K0, K1), (G0, G1), (P0_, P1_), (M0, M1) = (pieces[n] for n in ('Kt', 'KnS', 'GmS', 'Fnp', 'Fnm'))
    cf = 8 * a * lam * rh * M * x2 * (x2 + q0)
    Nk = [cf * Kt0 * K0 - at * (P0_ - M0) * u * K0 + an * (GpS.n - G0) * u * Kt0,
          cf * (Kt0 * K1 + Kt1 * K0) - at * ((P0_ - M0) * K1 + (P1_ - M1) * K0) * u
          + an * ((GpS.n - G0) * Kt1 - G1 * Kt0) * u,
          cf * Kt1 * K1 - at * (P1_ - M1) * u * K1 - an * G1 * Kt1 * u]
    Ic = F(cf) * Kt * KnS - F(at) * (fnp - fnm) * F(u) * KnS + F(an) * (GpS - GmS) * F(u) * Kt
    assert Ic.d.is_one() and Nk[0] + s * Nk[1] + s ** 2 * Nk[2] == Ic.n
    C = '8 * a * (4 * a ^ 2) * ρ * M * u ^ 2 * (u ^ 2 + a ^ 2 - w ^ 2 / 4)'
    p = {n: call(n) for n in ('Kt0W', 'Kt1W', 'KnS0W', 'KnS1W', 'GmS0W', 'GmS1W', 'Fnp0W', 'Fnp1W',
                              'Fnm0W', 'Fnm1W', 'GpSW', 'aAW', 'anW')}
    stmts = [
        [f"{C} *", f"    {p['Kt0W']} * {p['KnS0W']} -",
         f"  {p['aAW']} * ({p['Fnp0W']} - {p['Fnm0W']}) * u * {p['KnS0W']} +",
         f"  {p['anW']} * ({p['GpSW']} - {p['GmS0W']}) * u *", f"    {p['Kt0W']}"],
        [f"{C} *",
         f"    ({p['Kt0W']} * {p['KnS1W']} + {p['Kt1W']} * {p['KnS0W']}) -",
         f"  {p['aAW']} * (({p['Fnp0W']} - {p['Fnm0W']}) * {p['KnS1W']} +",
         f"    ({p['Fnp1W']} - {p['Fnm1W']}) * {p['KnS0W']}) * u +",
         f"  {p['anW']} * (({p['GpSW']} - {p['GmS0W']}) * {p['Kt1W']} -",
         f"    {p['GmS1W']} * {p['Kt0W']}) * u"],
        [f"{C} *", f"    {p['Kt1W']} * {p['KnS1W']} -",
         f"  {p['aAW']} * ({p['Fnp1W']} - {p['Fnm1W']}) * u * {p['KnS1W']} -",
         f"  {p['anW']} * {p['GmS1W']} * {p['Kt1W']} * u"]]
    names_k = ['Kt0W', 'Kt1W', 'KnS0W', 'KnS1W', 'GmS0W', 'GmS1W', 'Fnp0W', 'Fnp1W', 'Fnm0W', 'Fnm1W',
               'GpSW', 'aAW', 'anW']
    args_k = [x for x in ORDER if x in set().union(*(SIG[n] for n in names_k)) | {'u', 'a', 'w'}]
    for kk, (N_, st) in enumerate(zip(Nk, stmts)):
        q, r = divmod(N_, Eu)
        assert r.is_zero()
        used = [n for n in names_k if n in ''.join(st)]
        out.append(f'/-- The coefficient of `s^{kk}` of `sym_c`. -/')
        out.append(f'theorem sym_c{kk} ({" ".join(args_k)} : ℂ) (hE : {call("E8W")} = 0) :')
        st[-1] += ' = 0 := by'
        out.extend('    ' + ln for ln in st)
        out.append('  unfold E8W at hE')
        out.append(f'  unfold {" ".join(used)}')
        out.append('  linear_combination (exp := 1) (')
        out.append(wrap(lean_poly(q), indent=6))
        out.append('    ) * hE')
        out.append('')
        print(f'c{kk}', 'numerator terms', len(N_), 'quotient terms', len(q))
    c = {n: call(n) for n in ('KtW', 'KnSW', 'aAW', 'FnpW', 'FnmW', 'anW', 'GpSW', 'GmSW')}
    args_c = [x for x in ORDER if x in set().union(*(SIG[n] for n in c)) | {'u', 's', 'a', 'w'}]
    out.append('/-- At a root of `E₈`, the constant part of the residue of '
               '`Γ_L(-t, z; t, v) - Γ_L(t, v; -t, z)`. -/')
    out.append(f'theorem sym_c ({" ".join(args_c)} : ℂ) (hE : {call("E8W")} = 0) :')
    out.extend('    ' + ln for ln in [
        f"{C} *", f"    {c['KtW']} * {c['KnSW']} -",
        f"  {c['aAW']} * ({c['FnpW']} - {c['FnmW']}) * u *", f"    {c['KnSW']} +",
        f"  {c['anW']} * ({c['GpSW']} - {c['GmSW']}) * u *", f"    {c['KtW']} = 0 := by"])
    out.append('  rw [KtW_split, KnSW_split, GmSW_split, FnpW_split, FnmW_split]')
    hk = ' '.join(args_k)
    out.append(f'  linear_combination sym_c0 {hk} hE + s * sym_c1 {hk} hE +')
    out.append(f'    s ^ 2 * sym_c2 {hk} hE')
    out.append('')
    out.append('end LCert\n\nend HubbardAtom')
    open(os.path.join(outdir, 'FieldLSymCert.lean'), 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
